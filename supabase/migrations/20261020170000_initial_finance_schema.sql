-- Initial MedPlanner cloud schema.
-- Each row belongs to the authenticated account that created it.

create table public.expenses (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  title text not null,
  category text not null,
  amount_cents bigint not null check (amount_cents >= 0),
  month text not null check (month ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
  paid smallint not null default 0 check (paid in (0, 1)),
  due_date date
);

create table public.incomes (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  service text not null,
  quantity numeric(12, 3) not null check (quantity >= 0),
  unit_cents bigint not null check (unit_cents >= 0),
  date timestamptz not null,
  receive_month text not null check (receive_month ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
  tax_applies smallint not null default 0 check (tax_applies in (0, 1)),
  received smallint not null default 0 check (received in (0, 1)),
  investment_ids text not null default '*'
);

create table public.categories (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  name text not null,
  scope text not null check (scope in ('planning', 'cards', 'goals')),
  unique (user_id, name, scope)
);

create table public.services (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  name text not null,
  unit_cents bigint not null check (unit_cents >= 0),
  unique (user_id, name)
);

create table public.cards (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  name text not null,
  limit_cents bigint not null check (limit_cents >= 0),
  unique (user_id, id)
);

create table public.card_expenses (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  card_id bigint not null,
  title text not null,
  category text not null,
  amount_cents bigint not null check (amount_cents >= 0),
  installment_count integer not null check (installment_count >= 1),
  installment_index integer not null check (installment_index between 1 and installment_count),
  month text not null check (month ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
  recurring smallint not null default 0 check (recurring in (0, 1)),
  paid smallint not null default 0 check (paid in (0, 1)),
  purchase_id text,
  foreign key (user_id, card_id) references public.cards(user_id, id) on delete cascade
);

create table public.goals (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  title text not null,
  category text not null,
  description text not null default '',
  unit_cents bigint not null check (unit_cents >= 0),
  quantity integer not null check (quantity >= 1)
);

create table public.settings (
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  key text not null,
  value text not null,
  primary key (user_id, key)
);

create table public.investments (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  name text not null,
  mode text not null check (mode in ('percent', 'fixed')),
  value integer not null check (value >= 0)
);

create index expenses_user_month_idx on public.expenses(user_id, month);
create index incomes_user_receive_month_idx on public.incomes(user_id, receive_month);
create index card_expenses_user_card_month_idx on public.card_expenses(user_id, card_id, month);
create index goals_user_title_idx on public.goals(user_id, title);

-- Secure every app table. A client can only read or mutate rows owned by its
-- authenticated account; an account cannot assign another user's owner ID.
do $$
declare
  table_name text;
begin
  foreach table_name in array array[
    'expenses', 'incomes', 'categories', 'services', 'cards',
    'card_expenses', 'goals', 'settings', 'investments'
  ] loop
    execute format('alter table public.%I enable row level security', table_name);
    execute format('revoke all on public.%I from anon', table_name);
    execute format('grant select, insert, update, delete on public.%I to authenticated', table_name);
    execute format(
      'create policy %I on public.%I for select to authenticated using ((select auth.uid()) = user_id)',
      table_name || '_select_own', table_name
    );
    execute format(
      'create policy %I on public.%I for insert to authenticated with check ((select auth.uid()) = user_id)',
      table_name || '_insert_own', table_name
    );
    execute format(
      'create policy %I on public.%I for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id)',
      table_name || '_update_own', table_name
    );
    execute format(
      'create policy %I on public.%I for delete to authenticated using ((select auth.uid()) = user_id)',
      table_name || '_delete_own', table_name
    );
  end loop;
end;
$$;

-- Preserve the defaults currently created by the local SQLite database.
create or replace function public.seed_medplanner_user_defaults()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.categories (user_id, name, scope)
  select new.id, category_name, scope_name
  from unnest(array[
    'Vida', 'Mensal', 'Investimento', 'Mercado', 'Transporte',
    'Moradia', 'Saúde', 'Lazer', 'Outros'
  ]) as category_names(category_name)
  cross join unnest(array['planning', 'cards', 'goals']) as scopes(scope_name)
  on conflict (user_id, name, scope) do nothing;

  insert into public.investments (user_id, name, mode, value)
  values (new.id, 'Reserva', 'percent', 10);

  insert into public.settings (user_id, key, value)
  values (new.id, 'tax_percent', '0'), (new.id, 'tax_investment_tour_seen', '0');

  return new;
end;
$$;

create trigger on_auth_user_created_seed_medplanner_defaults
after insert on auth.users
for each row execute function public.seed_medplanner_user_defaults();
